package main

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"log/slog"
	"net/http"
	"os"
	"strings"
	"time"

	"github.com/Fadet/highload-hw1/internal/dashboard"
)

type config struct {
	appURLs         []string
	grafanaURL      string
	grafanaUser     string
	grafanaPassword string
	datasourceUID   string
	dashboardUID    string
	dashboardTitle  string
	timeout         time.Duration
}

type permanentError struct{ err error }

func (e permanentError) Error() string { return e.err.Error() }
func (e permanentError) Unwrap() error { return e.err }

func main() {
	cfg, err := loadConfig()
	if err != nil {
		slog.Error("invalid config", "err", err)
		os.Exit(2)
	}

	ctx, cancel := context.WithTimeout(context.Background(), cfg.timeout)
	defer cancel()

	if err := run(ctx, cfg, &http.Client{Timeout: 10 * time.Second}); err != nil {
		slog.Error("dashboard generation failed", "err", err)
		os.Exit(1)
	}
}

func run(ctx context.Context, cfg config, client *http.Client) error {
	handlers, err := fetchAllHandlers(ctx, client, cfg.appURLs)
	if err != nil {
		return err
	}
	slog.Info("fetched handlers", "count", len(handlers), "handlers", handlers)

	d := dashboard.Build(handlers, dashboard.Options{
		UID:           cfg.dashboardUID,
		Title:         cfg.dashboardTitle,
		DatasourceUID: cfg.datasourceUID,
	})

	url, err := withRetry(ctx, "upload dashboard", func() (string, error) {
		return uploadDashboard(ctx, client, cfg, d)
	})
	if err != nil {
		return err
	}
	slog.Info("dashboard uploaded", "url", strings.TrimRight(cfg.grafanaURL, "/")+url, "panels", len(d.Panels))
	return nil
}

func fetchAllHandlers(ctx context.Context, client *http.Client, appURLs []string) ([]dashboard.Handler, error) {
	var all []dashboard.Handler
	seen := map[dashboard.Handler]bool{}

	for _, base := range appURLs {
		handlers, err := withRetry(ctx, "fetch handlers from "+base, func() ([]dashboard.Handler, error) {
			return fetchHandlers(ctx, client, base)
		})
		if err != nil {
			return nil, err
		}
		for _, h := range handlers {
			if !seen[h] {
				seen[h] = true
				all = append(all, h)
			}
		}
	}

	if len(all) == 0 {
		return nil, errors.New("applications reported no handlers")
	}
	return all, nil
}

func fetchHandlers(ctx context.Context, client *http.Client, base string) ([]dashboard.Handler, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, strings.TrimRight(base, "/")+"/handlers", nil)
	if err != nil {
		return nil, permanentError{err}
	}

	resp, err := client.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()

	if err := checkStatus(resp); err != nil {
		return nil, err
	}

	var body struct {
		Handlers []dashboard.Handler `json:"handlers"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&body); err != nil {
		return nil, permanentError{fmt.Errorf("decode /handlers: %w", err)}
	}
	return body.Handlers, nil
}

func uploadDashboard(ctx context.Context, client *http.Client, cfg config, d dashboard.Dashboard) (string, error) {
	payload, err := json.Marshal(map[string]any{
		"dashboard": d,
		"overwrite": true,
		"message":   "generated by dashgen",
	})
	if err != nil {
		return "", permanentError{err}
	}

	req, err := http.NewRequestWithContext(ctx, http.MethodPost,
		strings.TrimRight(cfg.grafanaURL, "/")+"/api/dashboards/db", bytes.NewReader(payload))
	if err != nil {
		return "", permanentError{err}
	}
	req.Header.Set("Content-Type", "application/json")
	req.SetBasicAuth(cfg.grafanaUser, cfg.grafanaPassword)

	resp, err := client.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()

	if err := checkStatus(resp); err != nil {
		return "", err
	}

	var body struct {
		URL string `json:"url"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&body); err != nil {
		return "", permanentError{fmt.Errorf("decode grafana response: %w", err)}
	}
	return body.URL, nil
}

func checkStatus(resp *http.Response) error {
	if resp.StatusCode >= 200 && resp.StatusCode < 300 {
		return nil
	}
	msg, _ := io.ReadAll(io.LimitReader(resp.Body, 1024))
	err := fmt.Errorf("%s %s: status %d: %s",
		resp.Request.Method, resp.Request.URL, resp.StatusCode, strings.TrimSpace(string(msg)))
	if resp.StatusCode >= 400 && resp.StatusCode < 500 {
		return permanentError{err}
	}
	return err
}

func withRetry[T any](ctx context.Context, what string, fn func() (T, error)) (T, error) {
	backoff := 500 * time.Millisecond
	for attempt := 1; ; attempt++ {
		v, err := fn()
		if err == nil {
			return v, nil
		}

		var perm permanentError
		if errors.As(err, &perm) {
			return v, err
		}

		slog.Warn("attempt failed, retrying", "op", what, "attempt", attempt, "err", err, "backoff", backoff)
		select {
		case <-ctx.Done():
			return v, fmt.Errorf("%s: giving up: %w (last error: %v)", what, ctx.Err(), err)
		case <-time.After(backoff):
		}
		backoff = min(backoff*2, 5*time.Second)
	}
}

func loadConfig() (config, error) {
	cfg := config{
		grafanaURL:      getenv("GRAFANA_URL", "http://grafana:3000"),
		grafanaUser:     os.Getenv("GRAFANA_USER"),
		grafanaPassword: os.Getenv("GRAFANA_PASSWORD"),
		datasourceUID:   getenv("DATASOURCE_UID", "prometheus"),
		dashboardUID:    getenv("DASHBOARD_UID", "items-service"),
		dashboardTitle:  getenv("DASHBOARD_TITLE", "Items service: golden signals"),
	}

	for _, u := range strings.Split(getenv("APP_URLS", "http://app-1:8080"), ",") {
		if u = strings.TrimSpace(u); u != "" {
			cfg.appURLs = append(cfg.appURLs, u)
		}
	}
	if len(cfg.appURLs) == 0 {
		return cfg, errors.New("APP_URLS is empty")
	}

	if cfg.grafanaUser == "" || cfg.grafanaPassword == "" {
		return cfg, errors.New("GRAFANA_USER and GRAFANA_PASSWORD must be set")
	}

	timeout, err := time.ParseDuration(getenv("TIMEOUT", "2m"))
	if err != nil || timeout <= 0 {
		return cfg, fmt.Errorf("TIMEOUT must be a positive duration, got %q", os.Getenv("TIMEOUT"))
	}
	cfg.timeout = timeout

	return cfg, nil
}

func getenv(key, fallback string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return fallback
}
