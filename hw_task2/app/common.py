import json
import logging
import os
import random
import uuid
from datetime import datetime, timezone

EVENT_TYPES = ["page_view", "add_to_cart", "purchase"]
EVENT_WEIGHTS = [70, 20, 10]


def env(name: str, default=None, cast=str):
    v = os.environ.get(name)
    if v is None or v == "":
        if default is None:
            raise SystemExit(f"env {name} is required")
        return default
    return cast(v)


def setup_logging(pod_id: str) -> logging.Logger:
    logging.basicConfig(
        level=logging.INFO,
        format=f"%(asctime)s {pod_id} %(levelname)s %(message)s",
        datefmt="%H:%M:%S",
    )
    return logging.getLogger(pod_id)


def make_event(user_id: str, seq: int, poison_rate: float) -> dict:
    """Event model.

    event_id    - UUID
    user_id     - owner of the event (generated by exactly one producer pod)
    type        - page_view | add_to_cart | purchase
    seq         - per-user sequence number, 1, 2, 3, ... without gaps
    produced_at - generation time (UTC, ISO-8601)
    payload     - free-form JSON; payload.poison=true marks a poison event
    """
    etype = random.choices(EVENT_TYPES, EVENT_WEIGHTS)[0]
    payload = {"page": f"/item/{random.randint(1, 500)}"}
    if etype == "purchase":
        payload["amount"] = round(random.uniform(1, 300), 2)
    if random.random() < poison_rate:
        payload["poison"] = True
    return {
        "event_id": str(uuid.uuid4()),
        "user_id": user_id,
        "type": etype,
        "seq": seq,
        "produced_at": datetime.now(timezone.utc).isoformat(timespec="milliseconds"),
        "payload": payload,
    }


def encode(event: dict) -> bytes:
    return json.dumps(event, separators=(",", ":")).encode()


def decode(raw: bytes) -> dict:
    return json.loads(raw)
