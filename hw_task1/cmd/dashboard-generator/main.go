package main

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"log/slog"
	"net/http"
	"os"
	"strings"
	"time"
)

type config struct {
	grafanaURL    string
	grafanaUser   string
	grafanaPass   string
	appURLs       []string
	datasourceUID string
}

type handlerInfo struct {
	Method  string `json:"method"`
	Path    string `json:"path"`
	Handler string `json:"handler"`
}

const (
	attempts = 10
	backoff  = 3 * time.Second
)

var client = &http.Client{Timeout: 5 * time.Second}

func main() {
	cfg, err := loadConfig()
	if err != nil {
		slog.Error("config", "err", err)
		os.Exit(1)
	}
	if err := run(context.Background(), cfg); err != nil {
		slog.Error("generate dashboard", "err", err)
		os.Exit(1)
	}
}

func loadConfig() (config, error) {
	cfg := config{
		grafanaURL:    strings.TrimRight(os.Getenv("GRAFANA_URL"), "/"),
		grafanaUser:   os.Getenv("GRAFANA_USER"),
		grafanaPass:   os.Getenv("GRAFANA_PASSWORD"),
		datasourceUID: os.Getenv("DATASOURCE_UID"),
	}
	for u := range strings.SplitSeq(os.Getenv("APP_URLS"), ",") {
		if u = strings.TrimSpace(u); u != "" {
			cfg.appURLs = append(cfg.appURLs, strings.TrimRight(u, "/"))
		}
	}

	var missing []string
	for name, v := range map[string]string{
		"GRAFANA_URL": cfg.grafanaURL, "GRAFANA_USER": cfg.grafanaUser,
		"GRAFANA_PASSWORD": cfg.grafanaPass, "DATASOURCE_UID": cfg.datasourceUID,
	} {
		if v == "" {
			missing = append(missing, name)
		}
	}
	if len(cfg.appURLs) == 0 {
		missing = append(missing, "APP_URLS")
	}
	if len(missing) > 0 {
		return cfg, fmt.Errorf("required env not set: %s", strings.Join(missing, ", "))
	}
	return cfg, nil
}

func run(ctx context.Context, cfg config) error {
	handlers, err := collectHandlers(ctx, cfg.appURLs)
	if err != nil {
		return err
	}
	slog.Info("handlers discovered", "count", len(handlers), "handlers", handlers)

	payload, err := json.Marshal(map[string]any{
		"dashboard": buildDashboard(handlers, cfg.datasourceUID),
		"overwrite": true,
		"message":   "generated by dashboard-generator",
	})
	if err != nil {
		return err
	}

	var resp struct {
		URL     string `json:"url"`
		Version int    `json:"version"`
	}
	err = retry(ctx, "upload dashboard", func() error {
		req, err := http.NewRequestWithContext(ctx, http.MethodPost, cfg.grafanaURL+"/api/dashboards/db", bytes.NewReader(payload))
		if err != nil {
			return permanent(err)
		}
		req.Header.Set("Content-Type", "application/json")
		req.SetBasicAuth(cfg.grafanaUser, cfg.grafanaPass)
		return doJSON(req, &resp)
	})
	if err != nil {
		return err
	}
	slog.Info("dashboard uploaded", "url", cfg.grafanaURL+resp.URL, "version", resp.Version)
	return nil
}

func collectHandlers(ctx context.Context, appURLs []string) ([]string, error) {
	seen := map[string]bool{}
	var handlers []string
	for _, base := range appURLs {
		var list []handlerInfo
		err := retry(ctx, "fetch handlers from "+base, func() error {
			req, err := http.NewRequestWithContext(ctx, http.MethodGet, base+"/handlers", nil)
			if err != nil {
				return permanent(err)
			}
			return doJSON(req, &list)
		})
		if err != nil {
			return nil, err
		}
		for _, h := range list {
			if h.Handler != "" && !seen[h.Handler] {
				seen[h.Handler] = true
				handlers = append(handlers, h.Handler)
			}
		}
	}
	if len(handlers) == 0 {
		return nil, errors.New("no handlers discovered")
	}
	return handlers, nil
}

type permanentError struct{ error }

func permanent(err error) error { return permanentError{err} }

func doJSON(req *http.Request, out any) error {
	resp, err := client.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	body, err := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
	if err != nil {
		return err
	}
	if resp.StatusCode >= 300 {
		err := fmt.Errorf("%s %s: %s: %s", req.Method, req.URL, resp.Status, bytes.TrimSpace(body))
		if resp.StatusCode < 500 {
			return permanent(err)
		}
		return err
	}
	if err := json.Unmarshal(body, out); err != nil {
		return permanent(fmt.Errorf("%s %s: decode response: %w", req.Method, req.URL, err))
	}
	return nil
}

func retry(ctx context.Context, op string, fn func() error) error {
	var err error
	for i := 1; i <= attempts; i++ {
		if err = fn(); err == nil {
			return nil
		}
		var p permanentError
		if errors.As(err, &p) {
			return fmt.Errorf("%s: %w", op, p.error)
		}
		slog.Warn("retrying", "op", op, "attempt", i, "err", err)
		select {
		case <-time.After(backoff):
		case <-ctx.Done():
			return ctx.Err()
		}
	}
	return fmt.Errorf("%s: giving up after %d attempts: %w", op, attempts, err)
}
